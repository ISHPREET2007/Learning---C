#include <stdio.h>
int main()
{
    // here learn about relational operators,these are used in if statements.
    int a = 1, b = 0;

    if (a==b)
    {
        printf("Zero and One are equal.\n");
    }
    else
    {
        printf("Zero and one are not equal.\n");
    }
    if (a!=b)
    {
        printf("Zero and one are not equal.\n");
    }
    if (a>=b)
    {
        printf("True.\n");
    }
    else
    {
        printf("False\n");
    }
    if (a<=b)
    {
        printf("True.\n");
    }
    else
    {
        printf("False\n");
    }
    return 0;
    // <,> already done.
}